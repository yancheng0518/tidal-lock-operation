// Pack the original images and GLBs without changing a texel or a vertex.
// Run before build-entry.mjs whenever any of these source assets changes.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const project = new URL('../', import.meta.url);
const dist = existsSync(new URL('dist/index.html', project)) ? new URL('dist/', project) : project;
const target = new URL('scene-assets/', dist);
mkdirSync(target, { recursive: true });
const world = names => names.map(name => 'world-assets/' + name);
const materials = ['panel','floor','asphalt','paint','steel','wood','rock','spalled'];
const groups = [
  ['surfaces', false, world(materials.flatMap(name => [name+'-color.jpg', name+'-normal.jpg']))],
  ['harbour', false, world([
    'apron-mask.jpg','dam-face.webp','spray.webp','yard-signs.webp','stormbreak.webp','harbour-ibl.webp',
    ...['px','nx','py','ny','pz','nz'].map(face => 'yard-reflection-'+face+'.webp')
  ])],
  ['carbine', true, ['actor-assets/carbine.glb']],
  ['patrol', true, ['actor-assets/guard.glb','actor-assets/reflex.glb']]
];
const digest = data => createHash('sha256').update(data).digest('hex');
const manifest = groups.map(([name, compressed, paths]) => {
  const parts = paths.map(path => readFileSync(new URL(path, dist)));
  const raw = Buffer.concat(parts);
  const packed = compressed ? gzipSync(raw, { level: 9 }) : raw;
  const sha256 = digest(packed);
  const file = name + '-' + sha256.slice(0,16) + '.pack';
  writeFileSync(new URL(file, target), packed);
  const entries = paths.map((path,i) => [path, parts[i].length, digest(parts[i])]);
  return { file, compressed, size: packed.length, sha256, entries };
});
writeFileSync(new URL('manifest.js', target),
  '// Generated by scripts/build-scene-assets.mjs. Entries contain the original path, byte length and SHA-256.\n' +
  'export const packs = ' + JSON.stringify(manifest, null, 2) + ';\n'
);
console.log(manifest.map(p => p.file + ' (' + p.entries.length + ' assets, ' + p.size + ' bytes)').join('\n'));
